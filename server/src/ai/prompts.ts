/** P3 検証 NG 時の再生成指示 */
export function regenerateInstruction(errors: string[]): string {
  return `前回生成した SQL / 設定は静的検証で却下されました。以下のエラーを修正して再生成してください:
${errors.map(e => `- ${e}`).join('\n')}`;
}
