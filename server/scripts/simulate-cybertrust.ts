/** 巨大 CSV を先頭 n レコードだけ Shift-JIS のまま切り出す（引用符内の改行を跨がない） */
async function sampleCsv(path: string, n: number): Promise<Buffer> {
  const lines: string[] = [];
  let inQuotes = false;
  let records = 0;
  const rl = createInterface({
    input: createReadStream(path).pipe(iconv.decodeStream('Shift_JIS')),
    crlfDelay: Infinity,
  });
  for await (const line of rl) {
    lines.push(line);
    for (const ch of line) if (ch === '"') inQuotes = !inQuotes;
    if (!inQuotes) { records++; if (records > n) break; }
  }
  rl.close();
  return iconv.encode(lines.join('\r\n'), 'Shift_JIS');
}

